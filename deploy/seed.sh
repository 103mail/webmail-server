#!/bin/bash
# Emit a data-only seed for one Domain on stdout, as SQLite SQL (ADR 19). The
# schema comes from ../schema/webmail.sqlite.sql; setup.sh loads both into the
# Domain's database file.
#
# It writes one Customer with one User, a mailbox (which is also that user's
# calendar, see calendar.ListCalendars), an inbox folder and an alias, plus
# enough content that all four sections of the client show something: a mail
# thread with two messages, three meetings around today, and a direct chat.
#
# It also writes a second account on the same Domain, because a chat needs two
# people who can both sign in, and a cross-Domain chat is not something
# federation carries.
#
# Usage:  ./seed.sh <domain> <login> <display name> <alias email>

set -euo pipefail

DOMAIN=${1:?domain}
LOGIN=${2:?login}
NAME=${3:?display name}
ALIAS=${4:?alias email}

# bcrypt of "password". Every account in the local development stack uses it,
# matching what ../../webmail/syncdata.sh does to a synced database.
HASH='$2y$10$jO3R170QUVr5pj.eMO1bZuduB8SoSAuIpC1jrmtzwnh6vEWr.bqpW'

# A second party to exchange mail and chat with, on the other Domain, so the
# fixtures read like a federated deployment even though delivery is local.
if [[ "$DOMAIN" == "example.com" ]]; then
    PEER_EMAIL="mevdschee@103mail.com"; PEER_NAME="Maurits van der Schee"
else
    PEER_EMAIL="bob@example.com"; PEER_NAME="Bob Jansen"
fi

# The second local account, for the chat.
SECOND_EMAIL="carol@$DOMAIN"
SECOND_NAME="Carol de Vries"

# Meeting times are UTC; time_zone is the display zone stored alongside them
# (ADR 8). The wall clock hours are Amsterdam local, so they are converted
# here, with the date command following DST, which a fixed +02:00 would not.
amsterdam() { date -u -d "TZ=\"Europe/Amsterdam\" $1" '+%Y-%m-%d %H:%M:%S'; }
TODAY=$(date -u +%F)
TOMORROW=$(date -u -d tomorrow +%F)
STANDUP_START=$(amsterdam "$TODAY 09:00")
STANDUP_END=$(amsterdam "$TODAY 09:30")
REVIEW_START=$(amsterdam "$TOMORROW 10:00")
REVIEW_END=$(amsterdam "$TOMORROW 11:00")

cat <<SQL
-- Seed for $DOMAIN. Generated by deploy/seed.sh; edit that, not this.
--
-- Logins: $LOGIN and $SECOND_EMAIL, both with the password "password"

-- Rows refer forward to rows inserted below them.
PRAGMA foreign_keys = OFF;

-- The Customer, and the User inside it. mailbox.customer_id, folder.customer_id
-- and alias.customer_id carry foreign keys onto user(id) in this schema, so
-- customer 1 and user 1 have to line up.
INSERT INTO \`customer\` (\`id\`, \`name\`, \`default_mailbox_id\`) VALUES (1, '$NAME', 1);
INSERT INTO \`user\` (\`id\`, \`customer_id\`, \`username\`, \`password\`, \`name\`, \`is_admin\`)
  VALUES (1, 1, '$LOGIN', '$HASH', '$NAME', 1);

-- A mailbox is also a calendar. One inbox folder, one alias to send from.
INSERT INTO \`mailbox\` (\`id\`, \`customer_id\`, \`user_id\`, \`name\`, \`color\`, \`default_folder_id\`, \`default_alias_id\`)
  VALUES (1, 1, 1, '$ALIAS', 'red', 1, 1);
INSERT INTO \`folder\` (\`id\`, \`customer_id\`, \`mailbox_id\`, \`name\`) VALUES (1, 1, 1, 'Inbox');
INSERT INTO \`alias\` (\`id\`, \`customer_id\`, \`email\`, \`name\`, \`mailbox_id\`)
  VALUES (1, 1, '$ALIAS', '$NAME', 1);

-- The Domain this Server is authoritative for. Design 3 retires the
-- "customer_id IS NULL" singleton, so this row names its owning Customer.
INSERT INTO \`domain\` (\`id\`, \`name\`, \`customer_id\`) VALUES (1, '$DOMAIN', 1);

-- A second account on this Domain, so there are two people who can both sign
-- in and hold a live chat. The FK on mailbox.customer_id points at user(id) in
-- this schema, so the customer and user ids have to line up here too.
INSERT INTO \`customer\` (\`id\`, \`name\`, \`default_mailbox_id\`) VALUES (2, '$SECOND_NAME', 2);
INSERT INTO \`user\` (\`id\`, \`customer_id\`, \`username\`, \`password\`, \`name\`)
  VALUES (2, 2, '$SECOND_EMAIL', '$HASH', '$SECOND_NAME');
INSERT INTO \`mailbox\` (\`id\`, \`customer_id\`, \`user_id\`, \`name\`, \`color\`, \`default_folder_id\`, \`default_alias_id\`)
  VALUES (2, 2, 2, '$SECOND_EMAIL', 'blue', 2, 2);
INSERT INTO \`folder\` (\`id\`, \`customer_id\`, \`mailbox_id\`, \`name\`) VALUES (2, 2, 2, 'Inbox');
INSERT INTO \`alias\` (\`id\`, \`customer_id\`, \`email\`, \`name\`, \`mailbox_id\`)
  VALUES (2, 2, '$SECOND_EMAIL', '$SECOND_NAME', 2);

INSERT INTO \`contact\` (\`id\`, \`customer_id\`, \`email\`, \`name\`) VALUES
  (1, 1, '$PEER_EMAIL', '$PEER_NAME'),
  (2, 1, '$SECOND_EMAIL', '$SECOND_NAME'),
  (3, 2, '$ALIAS', '$NAME'),
  (4, 2, '$PEER_EMAIL', '$PEER_NAME');

-- ── Mail ────────────────────────────────────────────────────────────────────
-- Canonical rows first, then this user's projection of them (ADR 3).
INSERT INTO \`g_thread\` (\`id\`, \`subject_line\`, \`body_summary\`, \`created_at\`, \`updated_at\`) VALUES
  (1, 'Welcome to $DOMAIN', 'Everything here is local test data.', datetime('now', '-2 days'), datetime('now', '-1 day'));
INSERT INTO \`g_message\` (\`id\`, \`g_thread_id\`, \`sender_email\`, \`sender_name\`, \`body\`, \`created_at\`, \`sent_at\`) VALUES
  (1, 1, '$PEER_EMAIL', '$PEER_NAME', 'Hello $NAME, this thread was seeded by deploy/seed.sh so the mail section has something in it.', datetime('now', '-2 days'), datetime('now', '-2 days')),
  (2, 1, '$ALIAS', '$NAME', 'Replying to myself, which is what happens until federation is implemented.', datetime('now', '-1 day'), datetime('now', '-1 day'));
INSERT INTO \`g_subscription\` (\`id\`, \`g_thread_id\`, \`email\`) VALUES
  (1, 1, '$ALIAS'), (2, 1, '$PEER_EMAIL');
INSERT INTO \`thread\` (\`id\`, \`customer_id\`, \`folder_id\`, \`g_thread_id\`, \`read_at\`) VALUES
  (1, 1, 1, 1, NULL);
INSERT INTO \`message\` (\`id\`, \`customer_id\`, \`thread_id\`, \`g_message_id\`, \`read_at\`) VALUES
  (1, 1, 1, 1, NULL),
  (2, 1, 1, 2, datetime('now', '-1 day'));

-- ── Calendar ────────────────────────────────────────────────────────────────
-- Relative to today, so the default month view is never empty. The timed
-- meetings were converted from Amsterdam wall clock time above.
--
-- The all day meeting is deliberately not converted. ListMeetings buckets by
-- UTC day, so midnight to midnight UTC lands on exactly one day, while the
-- same span shifted by an offset would straddle two and draw the band twice.
INSERT INTO \`g_meeting\` (\`id\`, \`title\`, \`start_time\`, \`end_time\`, \`time_zone\`, \`is_all_day\`, \`organizer_email\`, \`organizer_name\`, \`description\`) VALUES
  (1, 'Standup', '$STANDUP_START', '$STANDUP_END',
   'Europe/Amsterdam', 0, '$ALIAS', '$NAME', 'Daily standup'),
  (2, 'Design review', '$REVIEW_START', '$REVIEW_END',
   'Europe/Amsterdam', 0, '$PEER_EMAIL', '$PEER_NAME', 'Walk through the federation design'),
  (3, 'Company day', datetime('now', 'start of day', '+3 days'), datetime('now', 'start of day', '+4 days'),
   'Europe/Amsterdam', 1, '$ALIAS', '$NAME', 'All day, no agenda');
INSERT INTO \`meeting\` (\`id\`, \`customer_id\`, \`g_meeting_id\`, \`mailbox_id\`, \`will_attend\`) VALUES
  (1, 1, 1, 1, 'yes'), (2, 1, 2, 1, 'maybe'), (3, 1, 3, 1, NULL);
INSERT INTO \`g_attendee\` (\`id\`, \`g_meeting_id\`, \`email\`, \`will_attend\`) VALUES
  (1, 1, '$ALIAS', 'yes'), (2, 2, '$ALIAS', 'maybe'), (3, 2, '$PEER_EMAIL', 'yes');

-- ── Chat ────────────────────────────────────────────────────────────────────
INSERT INTO \`g_chat\` (\`id\`, \`type\`, \`name\`, \`created_by_email\`) VALUES
  (1, 'direct', NULL, '$PEER_EMAIL');
INSERT INTO \`g_chat_participant\` (\`id\`, \`g_chat_id\`, \`email\`, \`role\`) VALUES
  (1, 1, '$PEER_EMAIL', 'creator'), (2, 1, '$ALIAS', 'member');
INSERT INTO \`g_chat_message\` (\`id\`, \`g_chat_id\`, \`sender_email\`, \`sender_name\`, \`body\`, \`created_at\`) VALUES
  (1, 1, '$PEER_EMAIL', '$PEER_NAME', 'Is the local stack up?', datetime('now', '-3 hours')),
  (2, 1, '$ALIAS', '$NAME', 'Looks like it.', datetime('now', '-2 hours'));
INSERT INTO \`chat\` (\`id\`, \`customer_id\`, \`mailbox_id\`, \`g_chat_id\`, \`last_read_message_id\`) VALUES
  (1, 1, 1, 1, 1);
INSERT INTO \`chat_message\` (\`id\`, \`customer_id\`, \`chat_id\`, \`g_chat_message_id\`, \`delivered_at\`, \`read_at\`) VALUES
  (1, 1, 1, 1, datetime('now', '-3 hours'), datetime('now', '-3 hours')),
  (2, 1, 1, 2, datetime('now', '-2 hours'), datetime('now', '-2 hours'));

-- The chat between the two local accounts. Both sides are projected, which is
-- what makes a live exchange between them possible.
INSERT INTO \`g_chat\` (\`id\`, \`type\`, \`name\`, \`created_by_email\`) VALUES
  (2, 'direct', NULL, '$ALIAS');
INSERT INTO \`g_chat_participant\` (\`id\`, \`g_chat_id\`, \`email\`, \`role\`) VALUES
  (3, 2, '$ALIAS', 'creator'), (4, 2, '$SECOND_EMAIL', 'member');
INSERT INTO \`g_chat_message\` (\`id\`, \`g_chat_id\`, \`sender_email\`, \`sender_name\`, \`body\`, \`created_at\`) VALUES
  (3, 2, '$ALIAS', '$NAME', 'Morning. Try typing here, it should arrive without a reload.', datetime('now', '-30 minutes'));
INSERT INTO \`chat\` (\`id\`, \`customer_id\`, \`mailbox_id\`, \`g_chat_id\`, \`last_read_message_id\`) VALUES
  (2, 1, 1, 2, 3),
  (3, 2, 2, 2, NULL);
INSERT INTO \`chat_message\` (\`id\`, \`customer_id\`, \`chat_id\`, \`g_chat_message_id\`, \`delivered_at\`, \`read_at\`) VALUES
  (3, 1, 2, 3, datetime('now', '-30 minutes'), datetime('now', '-30 minutes')),
  (4, 2, 3, 3, datetime('now', '-30 minutes'), NULL);

-- ── Notification templates ──────────────────────────────────────────────────
-- internal/notify can only send one of these rows; it never takes a body, which
-- is what keeps message content off email (ADR 4).
INSERT INTO \`email_template\` (\`id\`, \`name\`, \`language\`, \`sender_name\`, \`sender_email\`, \`subject\`, \`body\`, \`parameters\`) VALUES
  (1, 'invite', 'en', '$NAME', 'no-reply@$DOMAIN', 'You have a message waiting',
   'Hello,

Someone sent you a message on $DOMAIN. Open it here:

{{link}}

This link is personal and expires.
', 'link');

SQL
